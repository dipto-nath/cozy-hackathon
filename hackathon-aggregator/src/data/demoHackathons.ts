/** ISO timestamp `days` from now (end of day), so demo countdowns stay alive. */
function inDays(days: number): string {
  const d = new Date();
  d.setDate(d.getDate() + days);
  d.setHours(23, 59, 0, 0);
  return d.toISOString();
}

